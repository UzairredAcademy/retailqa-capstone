USE RetailQEDb;
GO

IF OBJECT_ID('AuditLog') IS NOT NULL DROP TABLE AuditLog;
IF OBJECT_ID('InventoryLedger') IS NOT NULL DROP TABLE InventoryLedger;
IF OBJECT_ID('Returns') IS NOT NULL DROP TABLE Returns;
IF OBJECT_ID('Shipments') IS NOT NULL DROP TABLE Shipments;
IF OBJECT_ID('Payments') IS NOT NULL DROP TABLE Payments;
IF OBJECT_ID('OrderItems') IS NOT NULL DROP TABLE OrderItems;
IF OBJECT_ID('Orders') IS NOT NULL DROP TABLE Orders;
IF OBJECT_ID('Products') IS NOT NULL DROP TABLE Products;
IF OBJECT_ID('Users') IS NOT NULL DROP TABLE Users;
IF OBJECT_ID('Customers') IS NOT NULL DROP TABLE Customers;
GO

CREATE TABLE Customers (
  CustomerId INT IDENTITY PRIMARY KEY,
  FullName NVARCHAR(150) NOT NULL,
  Email NVARCHAR(150) NOT NULL UNIQUE,
  Phone NVARCHAR(30) NOT NULL,
  Address NVARCHAR(250) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Users (
  UserId INT IDENTITY PRIMARY KEY,
  CustomerId INT NULL,
  Email NVARCHAR(150) NOT NULL UNIQUE,
  Password NVARCHAR(100) NOT NULL,
  Role NVARCHAR(30) NOT NULL,
  FailedAttempts INT NOT NULL DEFAULT 0,
  LockedUntil DATETIME2 NULL,
  CONSTRAINT FK_Users_Customers FOREIGN KEY(CustomerId) REFERENCES Customers(CustomerId)
);

CREATE TABLE Products (
  ProductId INT IDENTITY PRIMARY KEY,
  SKU NVARCHAR(50) NOT NULL UNIQUE,
  Name NVARCHAR(150) NOT NULL,
  Price DECIMAL(18,2) NOT NULL,
  StockQuantity INT NOT NULL,
  IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Orders (
  OrderId INT IDENTITY PRIMARY KEY,
  CustomerId INT NOT NULL,
  Status NVARCHAR(30) NOT NULL DEFAULT 'Created',
  Subtotal DECIMAL(18,2) NOT NULL,
  TaxAmount DECIMAL(18,2) NOT NULL,
  DiscountAmount DECIMAL(18,2) NOT NULL,
  Total DECIMAL(18,2) NOT NULL,
  CouponCode NVARCHAR(30) NULL,
  Address NVARCHAR(250) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  UpdatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_Orders_Customers FOREIGN KEY(CustomerId) REFERENCES Customers(CustomerId)
);

CREATE TABLE OrderItems (
  OrderItemId INT IDENTITY PRIMARY KEY,
  OrderId INT NOT NULL,
  ProductId INT NOT NULL,
  Quantity INT NOT NULL,
  UnitPrice DECIMAL(18,2) NOT NULL,
  LineTotal DECIMAL(18,2) NOT NULL,
  CONSTRAINT FK_OrderItems_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId),
  CONSTRAINT FK_OrderItems_Products FOREIGN KEY(ProductId) REFERENCES Products(ProductId)
);

CREATE TABLE Payments (
  PaymentId INT IDENTITY PRIMARY KEY,
  OrderId INT NOT NULL,
  Amount DECIMAL(18,2) NOT NULL,
  Status NVARCHAR(30) NOT NULL,
  TransactionRef NVARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_Payments_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId)
);

CREATE TABLE Shipments (
  ShipmentId INT IDENTITY PRIMARY KEY,
  OrderId INT NOT NULL UNIQUE,
  TrackingNumber NVARCHAR(60) NOT NULL,
  Status NVARCHAR(30) NOT NULL DEFAULT 'Preparing',
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  DeliveredAt DATETIME2 NULL,
  CONSTRAINT FK_Shipments_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId)
);

CREATE TABLE Returns (
  ReturnId INT IDENTITY PRIMARY KEY,
  OrderId INT NOT NULL,
  Reason NVARCHAR(300) NOT NULL,
  Status NVARCHAR(30) NOT NULL DEFAULT 'Requested',
  RefundAmount DECIMAL(18,2) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_Returns_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId)
);

CREATE TABLE InventoryLedger (
  LedgerId INT IDENTITY PRIMARY KEY,
  ProductId INT NOT NULL,
  OrderId INT NULL,
  ChangeQuantity INT NOT NULL,
  Reason NVARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_InventoryLedger_Products FOREIGN KEY(ProductId) REFERENCES Products(ProductId),
  CONSTRAINT FK_InventoryLedger_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId)
);

CREATE TABLE AuditLog (
  AuditId INT IDENTITY PRIMARY KEY,
  EntityType NVARCHAR(50) NOT NULL,
  EntityId INT NOT NULL,
  Action NVARCHAR(100) NOT NULL,
  Details NVARCHAR(1000) NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
